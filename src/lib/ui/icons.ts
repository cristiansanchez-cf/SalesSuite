export type IconName = keyof typeof ICONS;
export const isIconName = (x: string): x is IconName => Object.hasOwn(ICONS, x);

/** SVG completo (para {@html} en Svelte o set:html en Astro). */
export function iconSvg(name: IconName, size = 18, label?: string): string {
  const a11y = label ? `role="img" aria-label="${label.replace(/"/g, '&quot;')}"` : 'aria-hidden="true"';
  return `<svg class="co-icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" ${a11y}>${ICONS[name]}</svg>`;
}
